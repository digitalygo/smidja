func runeInRanges(r rune, ranges []runeRange) bool {
	lo, hi := 0, len(ranges)-1
	for lo <= hi {
		mid := (lo + hi) / 2
		switch {
		case r < ranges[mid].lo:
			hi = mid - 1
		case r > ranges[mid].hi:
			lo = mid + 1
		default:
			return true
		}
	}
	return false
}

func isZeroWidthRune(r rune) bool {
	if r < 0x0300 {
		return r == 0x00AD || r == 0x200B || (r >= 0x200C && r <= 0x200F)
	}
	return runeInRanges(r, zeroWidthRanges)
}

func isVariationSelector(r rune) bool {
	return (r >= 0xFE00 && r <= 0xFE0F) || (r >= 0xE0100 && r <= 0xE01EF)
}

func isRegionalIndicator(r rune) bool {
	return r >= 0x1F1E6 && r <= 0x1F1FF
}

func isWideRune(r rune) bool {
	if r < 0x1100 {
		return false
	}
	return runeInRanges(r, wideRanges)
}

func isCombiningMark(r rune) bool {
	if r < 0x0300 {
		return false
	}
	return runeInRanges(r, zeroWidthRanges) && !isVariationSelector(r) && r != 0x200B && !(r >= 0x200C && r <= 0x200F)
}

func isGraphemeJoiner(r rune) bool {
	return r == 0x200D
}
